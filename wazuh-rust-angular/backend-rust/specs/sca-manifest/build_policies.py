# Builds crates/provigil-agent/src/sca/policies/<policy>.yml from policies.json + settings.json
# (the checks: rules only) and catalog-*.yml (ProVigil's own text). Run from this folder:
#   python build_policies.py
import glob, json, os, yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'crates', 'provigil-agent', 'src', 'sca', 'policies')
PRODUCT = r'r:HKLM\SOFTWARE\Microsoft\Windows NT\CurrentVersion -> ProductName -> '
BUILD = r'r:HKLM\SOFTWARE\Microsoft\Windows NT\CurrentVersion -> CurrentBuildNumber -> n:^(\d+) compare '
SQL = r'r:HKLM\SOFTWARE\Microsoft\Microsoft SQL Server\Instance Names\SQL'
MS_BASELINES = 'https://learn.microsoft.com/windows/security/operating-system-security/device-management/windows-security-configuration-framework/windows-security-baselines'

# our own requirement overrides: Windows 10 and 11 both call themselves "Windows 10" in ProductName
OVERRIDE = {
    'provigil_win10': {'all': [PRODUCT + 'r:^Windows 10', BUILD + '< 22000']},
    'provigil_win11': {'all': [PRODUCT + 'r:^Windows 10|^Windows 11', BUILD + '>= 22000']},
}

# SOC 2 and GDPR come from each check's NIST 800-53 control family (ProVigil's own mapping), with the
# requirement ids the rules' alerts use, so a check and an alert land on the same requirement
SOC2 = {'AC': ['CC6.1', 'CC6.3'], 'IA': ['CC6.1', 'CC6.2'], 'SC': ['CC6.6', 'CC6.7'], 'CM': ['CC7.1', 'CC8.1'], 'AU': ['CC7.2'],
        'SI': ['CC7.1', 'CC7.2'], 'MP': ['CC6.7'], 'CP': ['A1.2'], 'RA': ['CC3.2'], 'PT': ['P4.1']}
GDPR = {'AU': 'IV_35.7.d', 'SI': 'IV_35.7.d'}  # monitoring; the other families protect data: IV_32.2


def compliance(c):
    fam = [x.split('-')[0] for x in c.get('nist_800_53', [])]
    soc2 = sorted({r for f in fam for r in SOC2.get(f, [])})
    gdpr = sorted({GDPR.get(f, 'IV_32.2') for f in fam})
    return {**c, 'soc_2': soc2, 'gdpr_IV': gdpr}


settings = {s['id']: s for s in json.load(open(os.path.join(HERE, 'settings.json'), encoding='utf-8'))}
policies = json.load(open(os.path.join(HERE, 'policies.json'), encoding='utf-8'))
catalog = {}
for f in sorted(glob.glob(os.path.join(HERE, 'catalog-*.yml'))):
    catalog.update(yaml.safe_load(open(f, encoding='utf-8')))
missing = [sid for sid in settings if sid not in catalog]
assert not missing, f'no text for {len(missing)} settings, e.g. {missing[:5]}'

os.makedirs(OUT, exist_ok=True)
names = []
for i, p in enumerate(policies):
    pid, system = p['policy'], p['applies_to']
    req = OVERRIDE.get(pid) or {p['requirements']['condition']: p['requirements']['rules']}
    if pid.startswith('provigil_sqlserver'):
        req = {'all': req.get('all', []) + [SQL]}
    windows = pid.startswith('provigil_win')
    doc = {
        'policy': {
            'id': pid,
            'name': f'ProVigil {system} hardening',
            'description': f'Security configuration checks for {system}, written by ProVigil from the vendor\'s public documentation'
            + (' and Microsoft\'s Windows security baselines.' if windows else '.'),
            'references': [MS_BASELINES] if windows else [],
        },
        'requirements': req,
    }
    if p['variables']:
        doc['variables'] = p['variables']
    checks = []
    for n, sid in enumerate(p['checks']):
        s, t = settings[sid], catalog[sid]
        checks.append({
            'id': 60000 + 1000 * i + n,
            'title': t['title'],
            'description': t['description'],
            'rationale': t['rationale'],
            'remediation': t['remediation'],
            'compliance': compliance(t['compliance']),
            'condition': s['condition'],
            'rules': s['rules'],
        })
    doc['checks'] = checks
    path = os.path.join(OUT, pid + '.yml')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# ProVigil configuration policy: {system}. Generated by specs/sca-manifest/build_policies.py; edit the catalog, not this file.\n')
        yaml.safe_dump(doc, f, sort_keys=False, allow_unicode=True, width=10000)
    names.append(pid)
    print(pid, len(checks))

# the list the agent compiles in (src/sca/mod.rs: BUILTIN = include!("policies/builtin.rs"))
with open(os.path.join(OUT, 'builtin.rs'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by specs/sca-manifest/build_policies.py\n[\n')
    for n in names:
        f.write(f'    include_str!("{n}.yml"),\n')
    f.write(']\n')
