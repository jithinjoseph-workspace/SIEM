//! ProVigil Endpoint Agent - Rootcheck & Driver Hook Scanner
//!
//! One scan: known rootkit / malware files, trojaned system programs, the Windows policy checks
//! (malware indicators, risky applications, hardening settings), NTFS alternate data streams,
//! system binaries masquerading in user folders and non-driver programs in the drivers folder.
//! The signature lists and their formats are in `rootcheck_signatures.rs`.
//!
//! Every finding, and the `Starting rootcheck scan.` / `Ending rootcheck scan.` lines, goes out
//! as a `rootcheck` event (`message` is what the manager's rules read); every finding also goes
//! out as a `rootcheck_alert` (title, severity, evidence, path) for the console.
//!
//! 100% clean-room Rust implementation (zero GPL derivation).

use std::collections::{BTreeSet, HashMap};
use std::fs;
use std::path::{Path, PathBuf};
use chrono::Utc;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use tracing::warn;

use crate::rootcheck_signatures::{self as sigs, FileSig, Policy, PolicyList, Test, TrojanSig};

/// Known critical system binaries that must ONLY reside in System32 / SysWOW64.
const SYSTEM_CORE_BINARIES: &[&str] = &[
    "smss.exe",
    "csrss.exe",
    "wininit.exe",
    "winlogon.exe",
    "services.exe",
    "lsass.exe",
    "svchost.exe",
    "taskhostw.exe",
    "explorer.exe",
];

/// Suspicious directory substrings where core system binaries must never reside.
pub const SUSPICIOUS_LOCATIONS: &[&str] = &[
    "temp",
    "tmp",
    "appdata",
    "users\\public",
    "programdata",
];

/// Standard named streams Windows itself writes (download origin, SmartScreen, EFS, compression).
const STANDARD_STREAMS: &[&str] = &["zone.identifier", "smartscreen", "encryptable", "wofcompresseddata"];

/// Folder levels searched for `*` file names, and for alternate data streams.
const FILE_SEARCH_DEPTH: usize = 6;
const ADS_DEPTH: usize = 4;

/// Alert generated by the Rootcheck engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RootcheckFinding {
    pub rule_id: u32,
    pub severity: String, // "CRITICAL", "HIGH", "MEDIUM", "LOW"
    pub title: String,
    /// For the newer checks, the exact `rootcheck` message.
    pub description: String,
    pub evidence: String,
    pub path: Option<String>,
}

/// Which checks a scan runs (`rootcheck_checks` in `provigil-agent.json`); all by default.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct RootcheckChecks {
    pub files: bool,
    pub trojans: bool,
    /// The malware, application and audit policies.
    pub policies: bool,
    pub ads: bool,
    /// Running processes, for the policies' process conditions.
    pub processes: bool,
    pub masquerading: bool,
    pub drivers: bool,
}

impl Default for RootcheckChecks {
    fn default() -> Self {
        Self { files: true, trojans: true, policies: true, ads: true, processes: true, masquerading: true, drivers: true }
    }
}

/// Configuration for Rootcheck.
#[derive(Debug, Clone)]
pub struct RootcheckConfig {
    pub enabled: bool,
    pub scan_files: bool,
    pub scan_trojans: bool,
    pub scan_policies: bool,
    /// Off: the policies' process conditions see no process.
    pub scan_processes: bool,
    pub scan_drivers: bool,
    pub scan_system_binaries: bool,
    pub scan_alternate_streams: bool,
    pub scan_paths: Vec<PathBuf>,
    pub drivers_dir: PathBuf,
    /// Where `*` file names of the files list are searched (`%SystemDrive%\`).
    pub search_root: PathBuf,
    /// Folders checked for alternate data streams.
    pub ads_paths: Vec<PathBuf>,
    pub files: Vec<FileSig>,
    pub trojans: Vec<TrojanSig>,
    pub policies: Vec<Policy>,
}

impl Default for RootcheckConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            scan_files: true,
            scan_trojans: true,
            scan_policies: true,
            scan_processes: true,
            scan_drivers: true,
            scan_system_binaries: true,
            scan_alternate_streams: true,
            scan_paths: vec![
                PathBuf::from("C:\\Windows\\Temp"),
                PathBuf::from("C:\\Users\\Public"),
            ],
            drivers_dir: PathBuf::from("C:\\Windows\\System32\\drivers"),
            search_root: PathBuf::from(expand("%SystemDrive%\\")),
            ads_paths: ["%WINDIR%", "%WINDIR%\\System32", "%ProgramFiles%", "%ProgramFiles(x86)%"]
                .iter()
                .map(|p| expand(p))
                .filter(|p| !p.contains('%'))
                .map(PathBuf::from)
                .collect(),
            files: sigs::builtin_files(),
            trojans: sigs::builtin_trojans(),
            policies: sigs::builtin_policies(),
        }
    }
}

impl RootcheckConfig {
    /// The agent settings' checks, base directory and extra lists.
    pub fn from_settings(cfg: &crate::config::AgentConfig) -> Self {
        let c = cfg.rootcheck_checks;
        let mut rc = RootcheckConfig {
            scan_files: c.files,
            scan_trojans: c.trojans,
            scan_policies: c.policies,
            scan_processes: c.processes,
            scan_alternate_streams: c.ads,
            scan_system_binaries: c.masquerading,
            scan_drivers: c.drivers,
            search_root: PathBuf::from(expand(&cfg.rootcheck_base_directory)),
            ..RootcheckConfig::default()
        };
        rc.add_lists(cfg.rootcheck_files_list.as_deref(), cfg.rootcheck_trojans_list.as_deref(), &cfg.rootcheck_policies);
        rc
    }

    /// Adds the lists from the configured files; a file that cannot be read or parsed is
    /// skipped with a warning.
    pub fn add_lists(&mut self, files: Option<&Path>, trojans: Option<&Path>, policies: &[PathBuf]) {
        fn load<T>(path: &Path, parse: fn(&str) -> Result<Vec<T>, String>) -> Vec<T> {
            match fs::read_to_string(path).map_err(|e| e.to_string()).and_then(|t| parse(&t)) {
                Ok(v) => v,
                Err(e) => {
                    warn!(file = %path.display(), error = %e, "Rootcheck list not loaded");
                    Vec::new()
                }
            }
        }
        if let Some(p) = files {
            self.files.extend(load(p, sigs::parse_files));
        }
        if let Some(p) = trojans {
            self.trojans.extend(load(p, sigs::parse_trojans));
        }
        for p in policies {
            self.policies.extend(load(p, sigs::parse_policies));
        }
    }
}

/// `%WINDIR%\x` → `C:\Windows\x`; an unknown variable stays as written.
pub fn expand(s: &str) -> String {
    let mut out = String::new();
    let mut rest = s;
    while let Some(a) = rest.find('%') {
        let after = &rest[a + 1..];
        let Some(b) = after.find('%') else { break };
        match std::env::var(&after[..b]) {
            Ok(v) if b > 0 => {
                out.push_str(&rest[..a]);
                out.push_str(&v);
                rest = &after[b + 1..];
            }
            _ => {
                out.push_str(&rest[..=a]);
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

/// Calls `f` for every file and folder under `dir`, `levels` deep; links and junctions are not
/// followed.
pub(crate) fn walk(dir: &Path, levels: usize, f: &mut dyn FnMut(&Path)) {
    if levels == 0 || !crate::collecting() {
        return;
    }
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        f(&p);
        if e.file_type().is_ok_and(|t| t.is_dir()) {
            walk(&p, levels - 1, f);
        }
    }
}

/// The policy message detail of a test that holds (`None`: it does not hold).
fn holds(test: &Test, processes: &[String]) -> Option<String> {
    match test {
        Test::File { path, content } => {
            let p = expand(path);
            let ok = match content {
                None => Path::new(&p).exists(),
                Some(r) => fs::read(&p).is_ok_and(|b| r.is_match(&b)),
            };
            ok.then(|| format!(" File: {p}."))
        }
        Test::Registry { key, value, data } => {
            let ok = match (value, data) {
                (None, _) => reg::exists(key),
                (Some(v), None) => reg::value(key, v).is_some(),
                (Some(v), Some(r)) => reg::value(key, v).is_some_and(|d| r.is_match(d.as_bytes())),
            };
            ok.then(|| match value {
                Some(v) => format!(" Registry: {key} -> {v}."),
                None => format!(" Registry: {key}."),
            })
        }
        Test::Process(r) => processes.iter().find(|n| r.is_match(n.as_bytes())).map(|n| format!(" Process: {n}.")),
    }
}

/// The policy's message when it matches.
pub fn evaluate(p: &Policy, processes: &[String]) -> Option<String> {
    let (mut detail, mut any_held, mut all_held) = (String::new(), false, true);
    for c in &p.conditions {
        let hit = holds(&c.test, processes);
        if hit.is_some() != c.negate {
            any_held = true;
            detail.push_str(&hit.unwrap_or_default());
        } else {
            all_held = false;
        }
    }
    let matched = if p.any { any_held } else { all_held };
    if !matched {
        return None;
    }
    let reference = if p.reference.is_empty() { String::new() } else { format!(" Reference: {} .", p.reference) };
    Some(format!("{} {}.{}{}", p.list.title(), p.name, detail, reference))
}

pub(crate) fn running_processes() -> Vec<String> {
    let mut sys = sysinfo::System::new();
    sys.refresh_processes();
    sys.processes().values().map(|p| p.name().to_string()).collect()
}

pub struct RootcheckScanner {
    config: RootcheckConfig,
}

impl RootcheckScanner {
    pub fn new(config: RootcheckConfig) -> Self {
        Self { config }
    }

    /// Performs a full rootcheck scan cycle: the `rootcheck` events (start line, findings, end
    /// line) and a `rootcheck_alert` per finding.
    pub fn scan(&self, agent_id: &str, agent_name: &str) -> Vec<Value> {
        if !self.config.enabled {
            return Vec::new();
        }
        let agent = json!({ "id": agent_id, "name": agent_name });
        let line = |message: &str| {
            json!({
                "event_type": "rootcheck",
                "timestamp": Utc::now().to_rfc3339(),
                "agent": agent,
                "location": "rootcheck",
                "message": message,
            })
        };
        let mut events = vec![line("Starting rootcheck scan.")];

        let mut findings = Vec::new();
        if self.config.scan_files {
            findings.extend(self.check_files());
        }
        if self.config.scan_trojans {
            findings.extend(self.check_trojans());
        }
        if self.config.scan_policies {
            findings.extend(self.check_policies());
        }
        if self.config.scan_alternate_streams {
            findings.extend(self.check_alternate_data_streams());
        }
        if self.config.scan_system_binaries {
            findings.extend(self.check_masquerading_binaries());
        }
        if self.config.scan_drivers {
            findings.extend(self.check_drivers_directory());
        }

        for finding in findings {
            events.push(line(&finding.description));
            events.push(json!({
                "event_type": "rootcheck_alert",
                "timestamp": Utc::now().to_rfc3339(),
                "agent": agent,
                "rootcheck": finding
            }));
        }
        // cut short by the stop: a partial scan is not reported
        if !crate::collecting() {
            return Vec::new();
        }
        events.push(line("Ending rootcheck scan."));
        events
    }

    /// Known rootkit / malware files present.
    pub fn check_files(&self) -> Vec<RootcheckFinding> {
        let mut found: Vec<(&FileSig, String)> = Vec::new();
        let mut by_name: HashMap<String, Vec<&FileSig>> = HashMap::new();
        for s in &self.config.files {
            match s.path.strip_prefix('*') {
                Some(name) => by_name.entry(name.to_lowercase()).or_default().push(s),
                None => {
                    let p = expand(&s.path);
                    if Path::new(&p).exists() {
                        found.push((s, p));
                    }
                }
            }
        }
        if !by_name.is_empty() {
            // one walk for all the names
            walk(&self.config.search_root, FILE_SEARCH_DEPTH, &mut |p| {
                let name = p.file_name().map(|n| n.to_string_lossy().to_lowercase()).unwrap_or_default();
                for s in by_name.get(&name).into_iter().flatten() {
                    found.push((*s, p.display().to_string()));
                }
            });
        }
        found
            .into_iter()
            .map(|(s, path)| RootcheckFinding {
                rule_id: 5103,
                severity: "CRITICAL".into(),
                title: format!("Rootkit or malware file: {}", s.name),
                description: format!("Rootkit '{}' detected by the presence of file '{}'.", s.name, path),
                evidence: format!("Reference: {}", s.reference),
                path: Some(path),
            })
            .collect()
    }

    /// System programs whose bytes match a known tampering pattern.
    pub fn check_trojans(&self) -> Vec<RootcheckFinding> {
        let mut out = Vec::new();
        for s in &self.config.trojans {
            let path = expand(&s.path);
            let Ok(bytes) = fs::read(&path) else { continue };
            if s.regex.is_match(&bytes) {
                out.push(RootcheckFinding {
                    rule_id: 5104,
                    severity: "CRITICAL".into(),
                    title: format!("Trojaned system program: {path}"),
                    description: format!("Trojaned version of file '{path}' detected. Signature used: '{}' ({}).", s.pattern, s.name),
                    evidence: format!("Reference: {}", s.reference),
                    path: Some(path),
                });
            }
        }
        out
    }

    /// The malware, application and audit policy checks.
    pub fn check_policies(&self) -> Vec<RootcheckFinding> {
        if self.config.policies.is_empty() {
            return Vec::new();
        }
        let processes = if self.config.scan_processes { running_processes() } else { Vec::new() };
        self.config
            .policies
            .iter()
            .filter_map(|p| {
                let message = evaluate(p, &processes)?;
                let (rule_id, severity) = match p.list {
                    PolicyList::Malware => (5105, "HIGH"),
                    PolicyList::Application => (5106, "MEDIUM"),
                    PolicyList::Audit => (5107, "MEDIUM"),
                };
                Some(RootcheckFinding {
                    rule_id,
                    severity: severity.into(),
                    title: format!("{} {}", p.list.title(), p.name),
                    evidence: message.clone(),
                    description: message,
                    path: None,
                })
            })
            .collect()
    }

    /// Named NTFS data streams other than the standard ones, in the configured folders.
    pub fn check_alternate_data_streams(&self) -> Vec<RootcheckFinding> {
        // a set: %WINDIR% also walks into System32
        let mut found = BTreeSet::new();
        for root in &self.config.ads_paths {
            walk(root, ADS_DEPTH, &mut |p| {
                for s in named_streams(p) {
                    if !STANDARD_STREAMS.contains(&s.to_lowercase().as_str()) {
                        found.insert(format!("{}:{}", p.display(), s));
                    }
                }
            });
        }
        found
            .into_iter()
            .map(|stream| RootcheckFinding {
                rule_id: 5108,
                severity: "MEDIUM".into(),
                title: "NTFS alternate data stream".into(),
                description: format!("NTFS Alternate data stream found: '{stream}'. Possible hidden content."),
                evidence: format!("Stream: {stream}"),
                path: Some(stream),
            })
            .collect()
    }

    /// Checks for critical system binaries masquerading in suspicious user directories.
    pub fn check_masquerading_binaries(&self) -> Vec<RootcheckFinding> {
        let mut findings = Vec::new();

        for base_dir in &self.config.scan_paths {
            if !base_dir.exists() {
                continue;
            }

            if let Ok(entries) = fs::read_dir(base_dir) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    if path.is_file() {
                        if let Some(file_name) = path.file_name().and_then(|f| f.to_str()) {
                            let lower = file_name.to_lowercase();
                            if SYSTEM_CORE_BINARIES.contains(&lower.as_str()) {
                                findings.push(RootcheckFinding {
                                    rule_id: 5101,
                                    severity: "CRITICAL".to_string(),
                                    title: format!("Trojan Masquerading Detected: {}", file_name),
                                    description: format!(
                                        "Core Windows system binary '{}' found in unauthorized location '{}'",
                                        file_name,
                                        path.display()
                                    ),
                                    evidence: format!("Path: {}", path.display()),
                                    path: Some(path.to_string_lossy().to_string()),
                                });
                            }
                        }
                    }
                }
            }
        }

        findings
    }

    /// Inspects the Windows drivers directory for anomalous or non-standard driver files.
    pub fn check_drivers_directory(&self) -> Vec<RootcheckFinding> {
        let mut findings = Vec::new();
        if !self.config.drivers_dir.exists() {
            return findings;
        }

        if let Ok(entries) = fs::read_dir(&self.config.drivers_dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_file() {
                    if let Some(ext) = path.extension().and_then(|e| e.to_str()) {
                        let ext_lower = ext.to_lowercase();
                        // Non-sys executable or script inside drivers folder
                        if ext_lower == "exe" || ext_lower == "bat" || ext_lower == "ps1" || ext_lower == "vbs" {
                            findings.push(RootcheckFinding {
                                rule_id: 5102,
                                severity: "HIGH".to_string(),
                                title: "Suspicious Non-Driver Executable in System32\\drivers".to_string(),
                                description: format!(
                                    "Found executable '{}' inside the Windows kernel drivers folder.",
                                    path.display()
                                ),
                                evidence: format!("File extension: {}", ext_lower),
                                path: Some(path.to_string_lossy().to_string()),
                            });
                        }
                    }
                }
            }
        }

        findings
    }
}

/// The named data streams of a file or folder (stream enumeration API).
#[cfg(windows)]
fn named_streams(path: &Path) -> Vec<String> {
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::Foundation::INVALID_HANDLE_VALUE;
    use windows_sys::Win32::Storage::FileSystem::{
        FindClose, FindFirstStreamW, FindNextStreamW, FindStreamInfoStandard, WIN32_FIND_STREAM_DATA,
    };
    let w: Vec<u16> = path.as_os_str().encode_wide().chain(Some(0)).collect();
    let mut d: WIN32_FIND_STREAM_DATA = unsafe { std::mem::zeroed() };
    let data = (&mut d as *mut WIN32_FIND_STREAM_DATA).cast();
    let h = unsafe { FindFirstStreamW(w.as_ptr(), FindStreamInfoStandard, data, 0) };
    if h == INVALID_HANDLE_VALUE {
        return Vec::new();
    }
    let mut out = Vec::new();
    loop {
        let end = d.cStreamName.iter().position(|&c| c == 0).unwrap_or(d.cStreamName.len());
        let name = String::from_utf16_lossy(&d.cStreamName[..end]);
        // ":name:$DATA"; the file's own content is "::$DATA"
        if let Some(n) = name.strip_prefix(':').and_then(|n| n.strip_suffix(":$DATA")).filter(|n| !n.is_empty()) {
            out.push(n.to_string());
        }
        if unsafe { FindNextStreamW(h, data) } == 0 {
            break;
        }
    }
    unsafe { FindClose(h) };
    out
}

#[cfg(not(windows))]
fn named_streams(_: &Path) -> Vec<String> {
    Vec::new()
}

/// Registry reads for the policy checks (64-bit view); also used by the configuration assessment.
#[cfg(windows)]
pub(crate) mod reg {
    use std::ptr::{null, null_mut};
    use windows_sys::Win32::Foundation::{ERROR_FILE_NOT_FOUND, ERROR_PATH_NOT_FOUND, ERROR_SUCCESS};
    use windows_sys::Win32::System::Registry::{
        RegCloseKey, RegOpenKeyExW, RegQueryValueExW, HKEY, HKEY_CLASSES_ROOT, HKEY_CURRENT_USER,
        HKEY_LOCAL_MACHINE, HKEY_USERS, KEY_READ, KEY_WOW64_32KEY, KEY_WOW64_64KEY, REG_DWORD, REG_EXPAND_SZ, REG_MULTI_SZ,
        REG_QWORD, REG_SZ,
    };

    fn wide(s: &str) -> Vec<u16> {
        s.encode_utf16().chain(Some(0)).collect()
    }

    struct Key(HKEY);

    impl Drop for Key {
        fn drop(&mut self) {
            unsafe { RegCloseKey(self.0) };
        }
    }

    /// `Ok(None)` when missing; `Err` when it cannot be read (access denied, unknown hive).
    fn status(rc: u32) -> Result<bool, String> {
        match rc {
            ERROR_SUCCESS => Ok(true),
            ERROR_FILE_NOT_FOUND | ERROR_PATH_NOT_FOUND => Ok(false),
            5 => Err("access denied".into()),
            rc => Err(format!("error {rc}")),
        }
    }

    fn open(key: &str) -> Result<Option<Key>, String> {
        let (root, sub) = key.split_once('\\').unwrap_or((key, ""));
        let root = match root.to_ascii_uppercase().as_str() {
            "HKLM" | "HKEY_LOCAL_MACHINE" => HKEY_LOCAL_MACHINE,
            "HKCU" | "HKEY_CURRENT_USER" => HKEY_CURRENT_USER,
            "HKU" | "HKEY_USERS" => HKEY_USERS,
            "HKCR" | "HKEY_CLASSES_ROOT" => HKEY_CLASSES_ROOT,
            _ => return Err(format!("unknown hive in {key}")),
        };
        // the 64-bit view, then the 32-bit one (`WOW6432Node`) when the key is not there
        for view in [KEY_WOW64_64KEY, KEY_WOW64_32KEY] {
            let mut h: HKEY = null_mut();
            if status(unsafe { RegOpenKeyExW(root, wide(sub).as_ptr(), 0, KEY_READ | view, &mut h) })? {
                return Ok(Some(Key(h)));
            }
        }
        Ok(None)
    }

    /// The key (`name` None: empty text when it exists) or the value's data as the SCA policies
    /// read it (see `sca_text`).
    pub fn query(key: &str, name: Option<&str>) -> Result<Option<String>, String> {
        match name {
            None => Ok(open(key)?.map(|_| String::new())),
            Some(n) => Ok(data(key, n)?.map(|(ty, b)| sca_text(ty, &b))),
        }
    }

    /// The value's type and bytes; `Ok(None)` when the key or value is missing.
    fn data(key: &str, name: &str) -> Result<Option<(u32, Vec<u8>)>, String> {
        let Some(k) = open(key)? else { return Ok(None) };
        let n = wide(name);
        let (mut ty, mut len) = (0u32, 0u32);
        if !status(unsafe { RegQueryValueExW(k.0, n.as_ptr(), null(), &mut ty, null_mut(), &mut len) })? {
            return Ok(None);
        }
        let mut buf = vec![0u8; len as usize];
        if !status(unsafe { RegQueryValueExW(k.0, n.as_ptr(), null(), &mut ty, buf.as_mut_ptr(), &mut len) })? {
            return Ok(None);
        }
        buf.truncate(len as usize);
        Ok(Some((ty, buf)))
    }

    pub fn exists(key: &str) -> bool {
        matches!(open(key), Ok(Some(_)))
    }

    /// The value's data as text (see the policies format); `None` when the key or value is missing.
    pub fn value(key: &str, name: &str) -> Option<String> {
        data(key, name).ok().flatten().map(|(ty, b)| text(ty, &b))
    }

    fn utf16(b: &[u8]) -> String {
        let w: Vec<u16> = b.as_chunks::<2>().0.iter().map(|c| u16::from_le_bytes(*c)).collect();
        String::from_utf16_lossy(&w)
    }

    fn hex(b: &[u8]) -> String {
        b.iter().map(|x| format!("{x:02x}")).collect()
    }

    pub fn text(ty: u32, b: &[u8]) -> String {
        match ty {
            REG_SZ | REG_EXPAND_SZ => utf16(b).trim_end_matches('\0').to_string(),
            REG_MULTI_SZ => utf16(b).split('\0').filter(|s| !s.is_empty()).collect::<Vec<_>>().join(" "),
            REG_DWORD if b.len() >= 4 => u32::from_le_bytes([b[0], b[1], b[2], b[3]]).to_string(),
            REG_QWORD if b.len() >= 8 => u64::from_le_bytes(b[..8].try_into().unwrap_or_default()).to_string(),
            _ => hex(b),
        }
    }

    /// The SCA policies' dialect: REG_MULTI_SZ strings each followed by a space, REG_QWORD as
    /// hex bytes; otherwise as `text`.
    pub fn sca_text(ty: u32, b: &[u8]) -> String {
        match ty {
            REG_MULTI_SZ => utf16(b).split('\0').filter(|s| !s.is_empty()).map(|s| format!("{s} ")).collect(),
            REG_QWORD => hex(b),
            _ => text(ty, b),
        }
    }
}

